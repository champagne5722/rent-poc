describe('normalizeAddress', () => {
  it.each(CASES)('%s：%s', (_label, raw, normalized, doorplate) => {
    const result = normalizeAddress(raw);
    expect(result.normalized).toBe(normalized);
    expect(result.doorplate).toBe(doorplate);
  });

  it('拆出路街、段、巷、弄、號、之號、樓、樓之號、室', () => {
    expect(normalizeAddress('台北市大安區羅斯福路三段283巷14弄5-1號10F-2 301室').parts).toEqual({
      county: '臺北市',
      district: '大安區',
      village: null,
      neighborhood: null,
      road: '羅斯福路',
      section: '3',
      lane: '283',
      alley: '14',
      number: '5',
      subNumber: '1',
      floor: '10',
      floorSub: '2',
      room: '301',
      rest: null,
    });
  });

  it('沒有路名時拆出村里與鄰', () => {
    const { parts } = normalizeAddress('花蓮縣秀林鄉崇德村三鄰十五號');
    expect(parts).toMatchObject({
      county: '花蓮縣',
      district: '秀林鄉',
      village: '崇德村',
      neighborhood: '3',
      road: null,
      number: '15',
    });
  });

  it('拆不出的字放在 rest，保留原字', () => {
    const { parts } = normalizeAddress('中山路100號附近');
    expect(parts.number).toBe('100');
    expect(parts.rest).toBe('附近');
  });

  it('完全拆不出時整串放在 rest', () => {
    const result = normalizeAddress('某某社區A棟');
    expect(result.parts.road).toBeNull();
    expect(result.parts.rest).toBe('某某社區A棟');
    expect(result.normalized).toBe('某某社區A棟');
  });
});
